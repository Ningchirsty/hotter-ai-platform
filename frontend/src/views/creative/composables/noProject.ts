/**
 * 「还没选项目」的统一回话（第 34 轮）。
 *
 * <p><b>为什么要有这个文件</b>：v1 人工测试反馈里「点了没反应」是一整类问题——
 * 按钮在、状态不对、点下去什么都不发生（最刺眼的是"品牌 brief 录入草稿后点确认没反应"、
 * "确认事实无误点下去没反应"）。第 23 轮把内容任务页的静默早退逐个清过一遍，
 * 但第 34 轮做了一次**可重复的静态审计**（`_local/audit-r34-silent-clicks.py`），
 * 又找出 7 处「刷新 / 加载」按钮：没有项目时直接 `return`，用户点下去没有任何回话。</p>
 *
 * <p><b>为什么是回话而不是把按钮置灰</b>：这些页面在"没选项目"时本来就有正常内容
 * （空态引导"先到视觉项目页选一个"），按钮置灰会让人以为是页面坏了；
 * 点一下得到一句"现在做不了，因为还没选项目"才是可理解的。置灰方案留给"选了项目也不能点"的场景。</p>
 *
 * <p><b>为什么口径只有一处</b>：同一句提示原先要是各页各写一份，迟早出现三种说法
 * （"没选项目"/"请先选择项目"/"未选择项目"）。这里一处定义，测试钉住。</p>
 *
 * @author creative
 */

import { ElMessage } from 'element-plus';

/** 「还没选项目」的标准提示语（各页共用；改动请连带更新单测） */
export const NO_PROJECT_HINT = '还没有选项目：请先到「视觉项目」页选一个项目，再回来操作';

/**
 * 弹一句「还没选项目」。
 *
 * <p>调用点都长这样：`if (!taskId) { notifyNoProject(); return; }`</p>
 */
export function notifyNoProject(): void {
  ElMessage.info(NO_PROJECT_HINT);
}
