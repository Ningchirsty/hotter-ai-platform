-- ============================================================================
-- AI 治理层 · 菜单权限增量迁移（存量环境用）
-- ----------------------------------------------------------------------------
-- 用途：`aig_ai_gov_menu.sql` 已随 main 发布并被部分环境执行过。该文件用的是普通
--       insert，重复执行会因主键冲突失败，因此后续新增的权限点不能靠「再跑一次」
--       铺开，需要本增量脚本。
--
-- 本次增量内容：新增模型能力所需的权限点 aig:model:add。
--   menu 1763000000000001204「模型新增」，授予：
--     - aig_admin    （AI数智化管理员）
--     - aig_security （信息安全授权人）
--   未授予 aig_viewer：该角色为全模块只读，新增模型属写操作。
--
-- 幂等：全部使用 insert ignore（按主键判重），可安全重复执行。
-- 顺序：需先存在父菜单 1763000000000000102（模型注册中心）与两个角色，
--       即先执行过 aig_ai_gov_menu.sql。
-- 回滚：见文件末尾注释。
-- ============================================================================

-- 1) 权限点：模型新增
insert ignore into sys_menu values(
  1763000000000001204, '模型新增', 1763000000000000102, 4, '', '', '', 'N', 'Y', 'F',
  '0', '0', 'aig:model:add', '#', '', '',
  1761000000000000103, 1761100000000000001, sysdate(), null, null,
  '登记 sai_model_config 主数据 + 首份治理属性');

-- 2) 授权：管理员 + 信息安全授权人
insert ignore into sys_role_menu values (1763100000000000001, 1763000000000001204);
insert ignore into sys_role_menu values (1763100000000000002, 1763000000000001204);

-- 3) 自检：应各返回一行
select '权限点' as item, m.menu_id, m.menu_name, m.perms
  from sys_menu m
 where m.menu_id = 1763000000000001204;

select '授权' as item, r.role_key, m.perms
  from sys_role_menu rm
  join sys_role r on r.role_id = rm.role_id
  join sys_menu m on m.menu_id = rm.menu_id
 where m.menu_id = 1763000000000001204
 order by r.role_key;

