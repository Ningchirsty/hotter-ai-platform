-- ============================================================================
-- 内容生产协同 · 品牌要求（Brief）权限独立（内测 C1 · 职责分离）
-- ----------------------------------------------------------------------------
-- 背景：Brief 的作者是品牌方，视觉工厂那边只读。但原先「保存」与「品牌方确认」
--       都只要 content:task:edit，而该权限在设计账号手里（内容角色同时拿到了整个
--       1767 段视觉工厂菜单）。于是「设计部能改品牌要求、还能自己点品牌方确认」
--       在权限层是成立的——内测真机实测过：一个只挂 content_member 的设计账号
--       可以写 Brief、改 Brief、并自己确认，审计里 confirmed_by 记的是设计师的 userId。
--
-- 本脚本做两件事：
--   1) 新增两个权限点：content:brief:edit（录入草稿）、content:brief:confirm（品牌方确认）
--   2) 授给品牌侧角色：content_admin 两个都给；content_member 只给录入
--      （与「签发开工包」同一口径：批准动作留给管理员级）
--
-- ⚠️ 上线顺序：**本脚本必须先于（或同时于）代码上线**。代码把 confirm 的权限换成
--    content:brief:confirm 之后，若库里还没有这个权限点、或没授给品牌角色，
--    品牌部会立刻点不了「品牌方确认」。
--
-- 幂等：INSERT IGNORE，可重复执行。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 一、权限点（按钮型菜单，挂在「内容任务」1765000000000000101 下）
--     1765 段的 17xx 号段此前未使用（16xx 是成品一致性检查）
-- ---------------------------------------------------------------------------
INSERT IGNORE INTO sys_menu
(menu_id, menu_name, parent_id, order_num, path, component, query_param, is_frame, is_cache, menu_type,
 visible, status, perms, icon, active_menu, ext, create_dept, create_by, create_time, update_by, update_time, remark)
VALUES
