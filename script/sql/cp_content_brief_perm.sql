 'content:brief:edit', '#', '', '', 1761000000000000103, 1761100000000000001, sysdate(), NULL, NULL,
 '录入并保存品牌要求草稿（品牌侧；视觉工厂只读）'),
(1765000000000001702, '品牌方确认', 1765000000000000101, 6, '', '', '', 'N', 'Y', 'F', '0', '0',
 'content:brief:confirm', '#', '', '', 1761000000000000103, 1761100000000000001, sysdate(), NULL, NULL,
 '品牌方确认这一版要求；视觉门的 BRAND_BRIEF_CONFIRMED 判的就是它');

-- ---------------------------------------------------------------------------
-- 二、授权
-- ---------------------------------------------------------------------------
INSERT IGNORE INTO sys_role_menu VALUES (1765100000000000001, 1765000000000001701);  -- content_admin  录入
INSERT IGNORE INTO sys_role_menu VALUES (1765100000000000001, 1765000000000001702);  -- content_admin  确认
INSERT IGNORE INTO sys_role_menu VALUES (1765100000000000002, 1765000000000001701);  -- content_member 仅录入

-- ---------------------------------------------------------------------------
-- 三、核对（期望：两个权限点各 1~2 个角色）
-- ---------------------------------------------------------------------------
SELECT m.menu_id, m.menu_name, m.perms,
       (SELECT COUNT(*) FROM sys_role_menu rm WHERE rm.menu_id = m.menu_id) AS granted_roles,
       (SELECT GROUP_CONCAT(r.role_key) FROM sys_role_menu rm JOIN sys_role r ON r.role_id = rm.role_id
         WHERE rm.menu_id = m.menu_id) AS roles
  FROM sys_menu m
 WHERE m.menu_id IN (1765000000000001701, 1765000000000001702);

