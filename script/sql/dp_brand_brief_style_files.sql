-- ==================================================================
-- 品牌 Brief 增加「参考风格图片」列（R7 追加）
--
-- 为什么需要：品牌方常常是"照这张图的风格做"，只给一段文字描述不够；
-- 参考风格只留一个文本框，等于逼着人把图片描述成文字（而且描述不准）。
--
-- 为什么存 file_id 列表（逗号分隔）而不是新建关联表：
--   1) 图片本身就是**任务附件**（落在 cp_task_file、走已有的上传与预览通路），
--      这里只记"哪几张是品牌给的风格参考"，是一份轻量的引用；
--   2) 参考图数量是个位数（服务端限 6 张），一张逗号列表足够，也便于人直接读库排障；
--   3) 不新建表就不用再造一套 Mapper/Service/权限，维护面最小。
--
-- 注意：MySQL 8 不支持 ADD COLUMN IF NOT EXISTS，本脚本只跑一次；
-- 列已存在时执行会报 Duplicate column，属预期（说明已迁过）。
-- ==================================================================

ALTER TABLE dp_brand_brief
  ADD COLUMN style_ref_files VARCHAR(1000) NULL COMMENT '参考风格图片（cp_task_file.file_id，逗号分隔，最多 6 张）'
  AFTER style_ref;
