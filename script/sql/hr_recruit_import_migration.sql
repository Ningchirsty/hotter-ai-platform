-- ============================================================================
-- 招聘管理 · 数据导入能力 增量脚本
-- ----------------------------------------------------------------------------
-- 背景：招聘期限标准与子公司月度招聘计划原界面只能逐条录入。
--       本次补齐「下载模板 → 上传预检 → 确认导入」的批量录入能力。
--
-- 本脚本只做两件事（菜单与权限按钮在原 hr_talent_menu.sql 里已全部存在，
-- 不需要新增菜单行）：
--   1. 取消隐藏「招聘标准」菜单——它的前端页面此前不存在，故种子时 visible='1'；
--      现在 hrtalent/standard/index 已实现，必须让它可见，否则用户进不去。
--   2. 把导入相关权限按钮授给「能看到这两张页面」的角色。
--      刻意用 INSERT ... SELECT 跟着页面权限走，而不是硬编码角色ID：
--      这样将来谁被授权了页面，导入权限自动跟上，不会漏。
--
-- 注意：「数据导入中心」菜单（1766000000000000112）保持隐藏不收口——
--       本次采用的是「各业务页面自带导入按钮」，该统一入口页面仍未实现，
--       放开会出现点进去 404 的死链。它的按钮权限行只作为权限载体使用。
--
-- 幂等：insert ignore + update，可安全重复执行。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 一、让「招聘标准」菜单可见
-- ---------------------------------------------------------------------------
update sys_menu set visible = '0' where menu_id = 1766000000000000111 and visible <> '0';

-- ---------------------------------------------------------------------------
-- 二、导入权限按钮授给相关角色
--     import:template / upload / confirm / cancel / detail 五个按钮
-- ---------------------------------------------------------------------------
insert ignore into sys_role_menu (role_id, menu_id)
select distinct rm.role_id, m.menu_id
  from sys_role_menu rm
  join sys_menu m on m.menu_id in (1766000000000002601, 1766000000000002602,
                                   1766000000000002603, 1766000000000002604,
                                   1766000000000002605)
 where rm.menu_id in (
         -- 公司月度计划
         1766000000000000103,
         -- 招聘标准
         1766000000000000111
       );

-- ---------------------------------------------------------------------------
-- 三、平台管理员补齐招聘标准的新增/编辑权限
--     其原授权只有 list/query，而本次交付的标准页面带「新增/编辑」按钮；
--     只读角色保持不变。
-- ---------------------------------------------------------------------------
insert ignore into sys_role_menu (role_id, menu_id)
select 1766100000000000001, m.menu_id
  from sys_menu m
 where m.menu_id in (1766000000000002503, 1766000000000002504);

-- ---------------------------------------------------------------------------
-- 四、自检
-- ---------------------------------------------------------------------------
select '招聘标准菜单可见性' as item, visible,
       case visible when '0' then '可见' else '隐藏' end as 说明
  from sys_menu where menu_id = 1766000000000000111;

select r.role_key as 角色,
       sum(case when rm.menu_id = 1766000000000000111 then 1 else 0 end) as 标准页面,
       sum(case when rm.menu_id in (1766000000000002601, 1766000000000002602,
                                    1766000000000002603, 1766000000000002604,
                                    1766000000000002605) then 1 else 0 end) as 导入权限数
  from sys_role_menu rm
  join sys_role r on r.role_id = rm.role_id
 where r.role_key in ('hr_platform_admin', 'hr_recruit_admin_group')
 group by r.role_key
 order by r.role_key;
