-- 14) 授权：把 1767 段全部菜单授予「已拥有内容任务菜单」的角色（= content_admin / content_member），
--     保证视觉工厂与内容协同的可见范围一致；INSERT IGNORE 幂等。
INSERT IGNORE INTO sys_role_menu (role_id, menu_id)
SELECT DISTINCT rm.role_id, m.menu_id
  FROM sys_role_menu rm
  JOIN sys_menu m
    ON m.menu_id BETWEEN 1767000000000000001 AND 1767000000000001699
 WHERE rm.menu_id = 1765000000000000101;

-- 15) 执行后核对（人工看一眼）
SELECT menu_id, parent_id, menu_name, menu_type, path, component, perms, order_num, icon, status
  FROM sys_menu
 WHERE menu_id BETWEEN 1767000000000000001 AND 1767000000000001699
 ORDER BY menu_id;

SELECT r.role_key, COUNT(*) AS granted
  FROM sys_role_menu rm
  JOIN sys_role r ON r.role_id = rm.role_id
 WHERE rm.menu_id BETWEEN 1767000000000000001 AND 1767000000000001699
 GROUP BY r.role_key
 ORDER BY r.role_key;

