package org.dromara.aigov.knowledge.pipeline;

/**
 * 嵌入端口（设计 §7.4；附件「知识处理引擎：按试点评测选型」）。
 *
 * <p><b>端口先行、模型后定</b>：附件明确"实际嵌入模型、向量存储和排序参数通过已批准资料的评测确定，
 * 不在本文件中宣称某方案已能达到准确率"。所以这里的接口只约定<b>形状</b>（文本进、定长向量出），
 * 不约定"用哪个模型"；默认实现是一个内部可部署的<b>可用性基线</b>，评测后替换实现即可，
 * 分段与索引链路不用改。</p>
 *
 * <h3>两条硬约束</h3>
 * <ul>
 *     <li><b>维度必须稳定</b>：同一引擎对同一文本永远返回同一维度——维度变了，已经写进索引的向量
 *         就全成了废数据，而检索只会表现为"分数莫名其妙"；</li>
 *     <li><b>确定性</b>：同一文本必须得到同一向量（否则同一份资料重建索引后，检索结果会莫名变化）。</li>
 * </ul>
 *
 * @author ai-gov
 */
public interface KnowledgeEmbeddingPort {

    /**
     * 引擎标识（写入索引，回答"这些向量是哪个模型产的"）。
     *
     * @return 稳定的引擎 ID
     */
    String engineId();

    /**
     * 向量维度。
     *
     * @return 维度（正整数）
     */
    int dimension();

    /**
     * 嵌入一段文本。
     *
     * @param text 文本（可空/空白 → 返回全零向量，由调用方决定是否使用）
     * @return 定长向量（长度 = {@link #dimension()}）
     */
    float[] embed(String text);

}
